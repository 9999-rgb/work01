def _scene_model_xml(model_path: str) -> str:
    """Return the scene model XML for ``/spawn_entity``.

    Scene models are authored as xacro (root ``<sdf>`` so Gazebo keeps the full
    meshes) in the description package; Gazebo's spawn service accepts raw
    SDF/URDF XML, not xacro, so a ``.xacro`` source is expanded here.  Plain
    SDF/URDF paths are passed through unchanged.
    """
    model_path = str(model_path)
    if model_path.endswith(".xacro"):
        # Lazy import: only needed when a scene model is xacro-authored, and it
        # keeps runner importable in envs without the ROS ``xacro`` package.
        # ``documentElement`` drops the XML declaration and xacro's
        # "autogenerated" banner comment, leaving a bare <sdf> root for spawn.
        import xacro

        return xacro.process_file(model_path).documentElement.toxml()
    return Path(model_path).read_text(encoding="utf-8")


def _scene_spec_signature(scene: SceneSpec) -> str:
    """Content signature for one scene spec.

    ``switch_scene`` uses this to tell a no-op re-switch (same name, same
    geometry/map/pose) from a re-import that changed the active scene's
    definition: a force re-import updates the catalog the gateway resolves
    against, and comparing names alone would silently keep the stale geometry
    on the world.
    """
    return json.dumps(
        scene.to_dict(), sort_keys=True, separators=(",", ":")
    )
