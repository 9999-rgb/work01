    def request_toolset_switch(
        self,
        toolset: str,
        *,
        expected_generation: int = 0,
    ) -> Dict[str, Any]:
        """Safely admit a world-preserving end-effector change.

        The actual model replacement runs in the ROS supervisor.  This method
        is the gateway-side safety boundary: it rejects live tasks/replay,
        validates the target A/B profile before stopping the old robot, and
        serializes the request with every other motion mutation.
        """
        if not isinstance(toolset, str) or toolset.strip().upper() not in {
            "A",
            "B",
        }:
            raise ControlRequestError("toolset must be A or B.", 400)
        target = toolset.strip().upper()
        with self._request_scope():
            with self._task_interlock_scope(check_toolset_ready=False):
                status = self._sync_toolset_runtime()
                if not status.get("managed"):
                    raise ControlRequestError(
                        "World-preserving toolset switching is unavailable in "
                        "this deployment.",
                        503,
                    )
                if status.get("state") != "ready" or not status.get("ready"):
                    raise ControlRequestError(
                        "Robot toolset is not ready for a new switch.",
                        409,
                        details={"toolset_status": status},
                    )
                if getattr(self, "_toolset_transition_generation", None) is not None:
                    raise ControlRequestError(
                        "A toolset switch result is still pending confirmation.",
                        409,
                        details={"toolset_status": status},
                    )
                if (
                    isinstance(expected_generation, bool)
                    or not isinstance(expected_generation, int)
                    or expected_generation < 0
                ):
                    raise ControlRequestError(
                        "expected_generation must be a non-negative integer.",
                        400,
                    )
                current_generation = status.get("generation")
                if (
                    isinstance(current_generation, bool)
                    or not isinstance(current_generation, int)
                    or current_generation < 0
                ):
                    raise ControlRequestError(
                        "Toolset supervisor reported an invalid generation.",
                        503,
                        details={"toolset_status": status},
                    )
                if (
                    expected_generation
                    and expected_generation != current_generation
                ):
                    raise ControlRequestError(
                        "Toolset status generation is stale; refresh status "
                        "and retry.",
                        409,
                        details={"toolset_status": status},
                    )
                self._validate_runtime_toolset(target)
                self._ensure_backend_quiescent("End-effector switch")
                self._quiesce_manual_outputs()
                # Set a fail-closed marker *before* dispatch.  The supervisor
                # may accept and begin replacing the robot even if the service
                # response is lost or arrives after the gateway's timeout.
                # Until a terminal status for this next generation arrives,
                # every motion path must remain interlocked.
                provisional_generation = current_generation + 1
                self._toolset_transition_generation = provisional_generation
                try:
                    accepted = self._node.request_toolset_switch(
                        target,
                        expected_generation=expected_generation,
                    )
                except ControlRequestError as error:
                    details = dict(getattr(error, "details", {}) or {})
                    response = details.get("toolset_response")
                    confirmed_unchanged = bool(
                        details.get("admission_uncertain") is False
                        and isinstance(response, Mapping)
                        and response.get("state") == "ready"
                        and response.get("generation") == current_generation
                        and response.get("active_toolset")
                        == status.get("active_toolset")
                    )
                    definitely_not_dispatched = bool(
                        details.get("admission_uncertain") is False
                        and response is None
                    )
                    if confirmed_unchanged or definitely_not_dispatched:
                        self._toolset_transition_generation = None
                    elif isinstance(response, Mapping):
                        response_generation = response.get("generation")
                        if (
                            isinstance(response_generation, int)
                            and not isinstance(response_generation, bool)
                            and response_generation > provisional_generation
                        ):
                            self._toolset_transition_generation = (
                                response_generation
                            )
                    raise
                self._toolset_transition_generation = int(
                    accepted["generation"]
                )
                return {
                    **accepted,
                    "toolset_status": self._sync_toolset_runtime(),
                }

    def scenes(self) -> Dict[str, Any]:
        """Return all switchable scenes (built-in + imported assets) and the
        currently active scene.

        Built-in scenes come from the shipped ``scenes.yaml``; imported scene
        assets are resolved lazily through the asset library so a Web import /
        delete is reflected without restart.  Entries carry a ``source`` field
        (``builtin`` | ``asset``) for the monitor's grouped dropdown; on a name
        collision the asset scene wins (it is the self-contained, importable
        copy the user selected).
        """
        with self._request_scope():
            builtin_catalog = getattr(self, "_builtin_scene_catalog", None)
            if builtin_catalog is None:
                builtin_catalog = getattr(self, "_scene_catalog", ())
            merged: Dict[str, Dict[str, Any]] = {}
            for scene in builtin_catalog:
                entry = scene.to_dict()
                entry["source"] = "builtin"
                merged[scene.name] = entry
            provider = getattr(self, "_asset_scene_provider", None)
            iterate = getattr(provider, "iter_scene_specs", None)
            if callable(iterate):
                for scene in iterate():
                    entry = scene.to_dict()
                    entry["source"] = "asset"
                    merged[scene.name] = entry
            # SCENES_CONFIG 覆盖且与出厂 scenes.yaml 分叉时，启动 catalog 里多出
            # 的场景仍可切换，必须出现在列表里，否则 Web 下拉无法选中它们。
            startup_catalog = getattr(self, "_scene_catalog", None)
            if startup_catalog is not None and startup_catalog is not builtin_catalog:
                for scene in startup_catalog:
                    if scene.name not in merged:
                        entry = scene.to_dict()
                        entry["source"] = "custom"
                        merged[scene.name] = entry
            # 活动场景必须始终在列表里：资产被删除后其 spec 仍缓存在
            # _scene_specs（供回切协调），_scene_lookup 仍能解析；若 /scenes
            # 漏掉它，Web 端无法高亮当前场景，切换按钮还会把默认目标错指到
            # 列表首个场景。
            active = getattr(self, "_active_scene", None)
            if active and active not in merged:
                try:
                    spec = self._scene_lookup(active)
                except SceneNotFoundError:
                    pass
                else:
                    entry = spec.to_dict()
                    entry["source"] = "asset"
                    merged[active] = entry
            return {
                "active": self._active_scene,
                "reconcile_pending": bool(
                    getattr(self, "_scene_reconcile_pending", False)
                ),
                "scenes": list(merged.values()),
            }

    def active_scene(self) -> Dict[str, Any]:
        """Return the currently active scene specification."""
        with self._request_scope():
            return self._scene_lookup(self._active_scene).to_dict()

    def _scene_lookup(self, name: str) -> SceneSpec:
        """Resolve a scene name across the asset library and the runtime registry.

        The provider is consulted first so an asset scene shadows a built-in
        scene with the same name; a resolved asset spec is cached in
        ``_scene_specs`` so a switch away still resolves ``previous`` after the
        asset is deleted.  Fake/legacy servers built without ``__init__`` fall
        back to ``_scene_catalog``.
        """
        provider = getattr(self, "_asset_scene_provider", None)
        resolve = getattr(provider, "resolve_scene", None)
        if callable(resolve):
            spec = resolve(name)
            if spec is not None:
                specs = getattr(self, "_scene_specs", None)
                if specs is not None:
                    specs[name] = spec
                return spec
        specs = getattr(self, "_scene_specs", None)
        if specs is not None and name in specs:
            return specs[name]
        catalog = getattr(self, "_scene_catalog", None)
        if catalog is not None:
            return catalog.get(name)
        raise SceneNotFoundError(name)

    def _resolve_navigation_keepout(self) -> Union[NavigationKeepoutConfig, None]:
        """Resolve the navigation keep-out band for the currently active scene.

        Precedence, in order:

          * explicit ``navigation_keepout: null`` in the scene spec -> ``None``
            (detour disabled; the two factory scenes have no cabinet-row band);
          * a declared mapping -> a :class:`NavigationKeepoutConfig`;
          * ``_UNSET`` (field absent) -> the shared robot adapter's band, the
            legacy behavior that keeps ``cabinet_operation``'s corridor without
            duplicating it per scene.

        ``_active_scene`` may be unset (no scene switched yet) or unresolvable
        in degraded states; either way the adapter band is the safe fallback.
        """
        active = getattr(self, "_active_scene", None)
        adapter_keepout = getattr(self._robot_adapter, "navigation_keepout", None)
        if not active:
            return adapter_keepout
        try:
            spec = self._scene_lookup(active)
        except SceneNotFoundError:
            return adapter_keepout
        value = getattr(spec, "navigation_keepout", _UNSET)
        if value is _UNSET:
            return adapter_keepout
        if value is None:
            return None
        return NavigationKeepoutConfig(**dict(value))

    def _require_cabinet_scene(self, operation: str) -> None:
        """Reject cabinet-scoped work when the active scene has no instances.

        Plant scenes without a fixture instance keep the cabinet/fixture C++
        operators running, so an unchecked operate/reset/navigate request would
        still be accepted against a deleted entity and fail (or report stale)
        later.  A scene is cabinet-capable exactly when at least one inventory
        instance (cabinet or fixture) declares it as ``associated_scene``; the
        scene catalog + inventory are the single source of truth.
        """
        catalog = getattr(self, "_scene_catalog", None)
        active_name = getattr(self, "_active_scene", None)
        # Legacy direct-route servers without the scene subsystem govern
        # cabinet work through the inventory only; never block them here.
        if catalog is None or active_name is None:
            return
        if getattr(self, "_scene_reconcile_pending", False):
            raise ControlRequestError(
                f"{operation} is unavailable: the last scene switch failed "
                "mid-way, leaving the world inconsistent with the recorded "
                f"scene '{active_name}'. Re-issue switch_scene to reconcile.",
                409,
            )
        if not self._scene_has_instances(active_name):
            raise ControlRequestError(
                f"{operation} is unavailable in scene "
                f"'{active_name}' (no cabinets/fixtures).",
                409,
            )

    def _scene_has_instances(self, scene_name: str) -> bool:
        """True when at least one inventory instance claims ``scene_name``."""
        inventory = getattr(self, "_inventory", None)
        if inventory is None:
            return True
        try:
            return any(
                getattr(instance, "associated_scene", "cabinet_operation")
                == scene_name
                for instance in inventory
            )
        except Exception:
            return True

    def _require_instance_scene(self, cabinet: str, operation: str) -> None:
        """Reject a per-instance request when its associated scene is inactive.

        The blanket :meth:`_require_cabinet_scene` only checks that SOME
        instance belongs to the active scene; this narrows the check to the
        named cabinet/fixture so e.g. a demo cabinet cannot be operated while
        the generator fixture scene is active.
        """
        active_name = getattr(self, "_active_scene", None)
        inventory = getattr(self, "_inventory", None)
        if active_name is None or inventory is None:
            return
        try:
            instance = inventory.get(cabinet)
        except CabinetNotFoundError as error:
            raise ControlRequestError(str(error), 404) from error
        if getattr(instance, "associated_scene", "cabinet_operation") != active_name:
            raise ControlRequestError(
                f"{operation} is unavailable: {cabinet} belongs to scene "
                f"'{instance.associated_scene}', not the active scene "
                f"'{active_name}'. Switch scenes first.",
                409,
            )

    def switch_scene(self, name: str) -> Dict[str, Any]:
        """Switch to another scene by reconciling Gazebo geometry, the Nav2
        map and the robot pose.

        The switch is serialized against concurrent switches by
        ``_scene_switch_lock`` and against task admission / manual control by
        ``_task_interlock_scope`` + ``_ensure_backend_quiescent``.  Geometry is
        reconciled with delete-then-spawn, so re-issuing a switch after a
        partial failure converges to the target scene.

        A failed switch marks ``_scene_reconcile_pending``: the world may not
        match ``_active_scene`` any more, so a re-switch to the recorded scene
        runs full reconciliation (status ``reconciled``) instead of short-
        circuiting to ``unchanged``, and cabinet-scoped operations are refused
        until the next switch succeeds.
        """
        if not isinstance(name, str) or not name.strip():
            raise ControlRequestError(
                "scene name must be a non-empty string.",
                400,
            )
        with self._request_scope():
            try:
                target = self._scene_lookup(name.strip())
            except SceneNotFoundError as error:
                raise ControlRequestError(str(error), 404) from error
            self._await_canceling_task_quiescence()
            with self._task_interlock_scope():
                self._ensure_backend_quiescent("Scene switch")
                with self._scene_switch_lock:
                    previous = self._active_scene
                    # Only short-circuit when the spec the world already
                    # matches is still the one requested: a force re-import
                    # that changed this scene's geometry/map/pose must fall
                    # through to reconciliation, or the new definition would
                    # silently never take effect.  Fake/legacy servers built
                    # without ``__init__`` have no signature map and keep the
                    # historical name-only behavior.
                    applied_signatures = getattr(
                        self, "_applied_scene_signatures", None
                    )
                    if (
                        previous == target.name
                        and not getattr(
                            self, "_scene_reconcile_pending", False
                        )
                        and (
                            applied_signatures is None
                            or applied_signatures.get(target.name)
                            == _scene_spec_signature(target)
                        )
                    ):
                        return {"status": "unchanged", "scene": target.name}
                    # Advertise the maintenance window through /health so the
                    # bridge liveness monitor treats the bounded map/geometry
                    # reconciliation as a hold instead of a dead stack.  The
                    # flag is cleared even when the switch raises.
                    self._scene_switch_in_progress = True
                    try:
                        self._apply_scene_switch(previous, target)
                    except BaseException:
                        # ``_apply_scene_switch`` sets ``_scene_reconcile_pending``
                        # just before the first world mutation, so the flag is
                        # already correct for any failure that could have left the
                        # world diverged from the recorded scene.  A failure
                        # before any mutation (e.g. load_map with the map_server
                        # down) leaves the world identical to ``previous`` and
                        # must not lock cabinet work behind a false pending flag.
                        raise
                    finally:
                        self._scene_switch_in_progress = False
                    # Success: the world now matches ``target``.  A previously
                    # pending reconciliation is resolved whether this switch
                    # converged back to the recorded scene or to a different
                    # one.
                    self._scene_reconcile_pending = False
                    self._active_scene = target.name
                    applied_signatures = getattr(
                        self, "_applied_scene_signatures", None
                    )
                    if applied_signatures is not None:
                        applied_signatures[target.name] = (
                            _scene_spec_signature(target)
                        )
                    return {
                        "status": (
                            "switched"
                            if previous != target.name
                            else "reconciled"
                        ),
                        "scene": target.name,
                        "previous": previous,
                    }

    def _apply_scene_switch(self, previous_name: str, target: SceneSpec) -> None:
        """Reconcile geometry, map and robot pose to ``target``.

        ``_active_scene`` is only advanced by the caller after this returns,
        so a raised error leaves the recorded scene at ``previous`` even if
        geometry is partially reconciled.
        """
        previous = self._scene_lookup(previous_name)
        try:
            # Load the Nav2 map first.  It is the most likely external call to
            # fail (map_server rejects bad metadata), and doing it before any
            # geometry change keeps the world intact when it does.  ``package://``
            # references are resolved to a filesystem path because this
            # map_server is launched without a resolver and rejects URIs.
            self._node.load_map(str(resolve_package_uri(target.nav2_map)))
            # From here the world may diverge from the recorded scene, so any
            # failure is a reconciliation-pending state.  A failure *before*
            # this point (load_map with the map_server down) leaves the world
            # identical to the recorded scene and must not lock cabinet work.
            self._scene_reconcile_pending = True
            if previous.model is not None:
                self._gazebo_client.delete_entity(
                    SCENE_FLOOR_ENTITY, ignore_missing=True
                )
            if previous.spawn_cabinet:
                self._delete_cabinet_entities()
            # Pass 1 — home in the cleared environment: the retiring scene's
            # geometry is gone and the incoming scene's floor/model is not yet
            # spawned.  Homing *after* the incoming geometry appears lets the
            # new structure collide with the robot still standing at the old
            # pose and push its arm away from home mid-motion (the reverse-
            # switch homing timeout).  Teleport afterwards, once the arm is
            # tucked, so an extended posture is never carried into a foreign
            # location.
            self._home_robot_joints(None, self._robot_entity_name)
            self._teleport_robot(target.robot_spawn)
            if target.model is not None:
                self._spawn_scene_floor(target.model)
            if target.spawn_cabinet:
                self._spawn_cabinet_entities()
            # Pass 2 — re-home once the incoming geometry is live.  Inserting a
            # large static mesh (or the cabinet cluster) into a running world
            # perturbs the articulated robot (a broadphase insertion kick) and
            # can nudge the tucked arm away from the defaults.  The pass is a
            # fast-path no-op when the arm is still home, and pulls it back to
            # the adapter defaults when a spawn moved it, so a scene switch
            # never hands the caller a robot left off its nominal posture.
            self._home_robot_joints(None, self._robot_entity_name)
        except ControlRequestError:
            raise
        except (
            CabinetSpawnError,
            SceneError,
            OSError,
            ValueError,
            TaskExecutionError,
        ) as error:
            # Surface structured failure context (e.g. the homing
            # ``observed_positions`` that explain an out-of-tolerance joint)
            # instead of swallowing it into a bare message.
            details = {}
            for source in (
                getattr(error, "details", None),
                getattr(error, "result", None),
            ):
                if isinstance(source, Mapping):
                    details.update(source)
            raise ControlRequestError(
                f"Scene switch to '{target.name}' failed: {error}",
                503,
                details=details or None,
            ) from error

    def _delete_cabinet_entities(self) -> None:
        for cabinet in self._inventory:
            if cabinet.kind != "cabinet":
                continue
            self._gazebo_client.delete_entity(
                cabinet.name, ignore_missing=True
            )

    def _spawn_cabinet_entities(self) -> None:
        button_defaults, button_profiles = read_button_profiles(
            self._cabinet_controls_path
        )
        for cabinet in self._inventory:
            # ``kind: fixture`` instances are carried by the scene model's own
            # plugin (per-scene control schema); spawning a shared cabinet URDF
            # for them would plant a phantom cabinet at the fixture's pose and
            # double-register the namespace.
            if cabinet.kind != "cabinet":
                continue
            urdf = build_cabinet_urdf(
                self._cabinet_xacro_path,
                cabinet.name,
                button_defaults,
                button_profiles,
            )
            self._gazebo_client.delete_entity(
                cabinet.name, ignore_missing=True
            )
            self._gazebo_client.spawn_entity(
                cabinet.name,
                urdf,
                pose=(
                    cabinet.x,
                    cabinet.y,
                    cabinet.z,
                    cabinet.roll,
                    cabinet.pitch,
                    cabinet.yaw,
                ),
                reference_frame="world",
            )

    def _spawn_scene_floor(self, model: SceneModel) -> None:
        try:
            model_path = resolve_package_uri(model.file)
            xml = _scene_model_xml(model_path)
        except (OSError, ValueError) as error:
            raise ControlRequestError(
                f"Could not read scene model '{model.file}': {error}",
                503,
            ) from error
        self._gazebo_client.delete_entity(
            SCENE_FLOOR_ENTITY, ignore_missing=True
        )
        self._gazebo_client.spawn_entity(
            SCENE_FLOOR_ENTITY,
            xml,
            pose=model.pose,
            reference_frame="world",
        )

    def _teleport_robot(self, robot_spawn: Optional[RobotSpawn]) -> None:
        if robot_spawn is None:
            return
        # ``base_link`` is a fixed child of the root ``body`` link rotated
        # -pi/2 about Z.  To point base_link at ``yaw`` in the map/world frame
        # the body must be rotated forward by pi/2.
        body_yaw = robot_spawn.yaw + math.pi / 2.0
        self._gazebo_client.set_entity_state(
            self._robot_entity_name,
            x=robot_spawn.x,
            y=robot_spawn.y,
            z=robot_spawn.z,
            yaw=body_yaw,
            reference_frame="world",
        )
        # The planar mover publishes at 20 Hz; publishing ``/initialpose`` before
        # a fresh odom frame propagates makes AMCL solve map->odom against the
        # *pre-teleport* pose and localize the robot tens of metres off (observed
        # after a scene switch).  Wait for the teleport to reach the odometry the
        # hypothesis is processed against, then publish -- and confirm AMCL's map
        # pose converged, re-publishing the hypothesis (bounded) if it did not.
        self._node.wait_for_planar_odom(
            robot_spawn.x,
            robot_spawn.y,
            body_yaw,
            tolerance_xy=0.06,
            tolerance_yaw=0.15,
            timeout_sec=5.0,
        )
        self._node.publish_initial_pose(
            robot_spawn.x,
            robot_spawn.y,
            robot_spawn.yaw,
            frame_id=self._robot_adapter.navigation_frame,
        )
        if not self._confirm_localization(
            robot_spawn.x,
            robot_spawn.y,
            robot_spawn.yaw,
            attempts=2,
            settle_sec=3.0,
        ):
            # Best-effort: the hypothesis was published against a fresh odom
            # frame, which is the actual fix.  A marginal AMCL lag here should
            # not fail the whole scene switch.
            logger.info(
                "scene switch: AMCL did not confirm spawn pose within tolerance"
            )

    def _confirm_localization(
        self,
        x: float,
        y: float,
        yaw: float,
        *,
        attempts: int,
        settle_sec: float,
    ) -> bool:
        """Wait for AMCL's map pose to converge to the teleported pose.

        Returns True once ``/amcl_pose`` (map frame, base_link) is within a
        coarse tolerance of ``(x, y, yaw)`` -- a check that cleanly separates a
        correct localization from the pre-teleport-odom mis-localization this
        teleport sequence exists to prevent.  A miss is not fatal to the switch.
        """
        navigation_frame = self._robot_adapter.navigation_frame
        for _ in range(max(1, int(attempts))):
            deadline = time.monotonic() + max(0.0, float(settle_sec))
            while time.monotonic() < deadline:
                pose = self._node.localized_pose()
                if pose is not None and pose.get("frame_id") == navigation_frame:
                    dx = pose["x"] - float(x)
                    dy = pose["y"] - float(y)
                    dyaw = _wrap_angle(pose["yaw"] - float(yaw))
                    if (
                        dx * dx + dy * dy <= 0.8 ** 2
                        and abs(dyaw) <= 0.4
                    ):
                        return True
                time.sleep(0.1)
            # Re-seed AMCL with the same hypothesis before the next settle.
            self._node.publish_initial_pose(
                x,
                y,
                yaw,
                frame_id=navigation_frame,
            )
        return False

